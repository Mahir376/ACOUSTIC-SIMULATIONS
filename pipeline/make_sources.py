"""Generates the synthetic source signals in SAMPLES/."""

import os

import numpy as np
from scipy.io import wavfile
from scipy.signal import butter, sosfilt

FS = 24000
rng = np.random.default_rng(7)


def bp(x, lo, hi):
    return sosfilt(butter(2, [lo, hi], btype="band", fs=FS, output="sos"), x)


def burst(dur, lo, hi, decay):
    n = int(dur * FS)
    return bp(rng.standard_normal(n), lo, hi) * np.exp(-np.arange(n) / (decay * FS))


def place(total_s, times, make):
    out = np.zeros(int(total_s * FS))
    for t in times:
        b = make()
        a = int(t * FS)
        m = min(len(b), len(out) - a)
        out[a:a + m] += b[:m]
    return out


def footsteps():
    def one():
        heel = burst(0.18, 60, 900, 0.03) * rng.uniform(0.8, 1.0)
        toe = np.concatenate([np.zeros(int(0.09 * FS)), burst(0.12, 300, 3000, 0.015) * 0.4])
        n = max(len(heel), len(toe))
        return np.pad(heel, (0, n - len(heel))) + np.pad(toe, (0, n - len(toe)))
    return place(4.6, 0.2 + 0.55 * np.arange(8), one)


def water_tap():
    n = 5 * FS
    x = bp(rng.standard_normal(n), 500, 9000)
    mod = 1 + 0.25 * bp(rng.standard_normal(n), 1, 12) / 0.05
    return x * np.clip(mod, 0.4, 1.8)


def cooking():
    n = 5 * FS
    x = 0.5 * bp(rng.standard_normal(n), 2500, 10000)
    return x + place(5, rng.uniform(0, 4.9, 120), lambda: burst(0.02, 3000, 11000, 0.003) * rng.uniform(0.5, 2))


def keyboard():
    times = np.cumsum(rng.uniform(0.09, 0.3, 30))
    return place(times[-1] + 0.3, times, lambda: burst(0.05, 1500, 9000, 0.006) * rng.uniform(0.6, 1.0))


def cutlery():
    def ping():
        n = int(0.35 * FS)
        t = np.arange(n) / FS
        f0 = rng.uniform(2200, 3800)
        return sum(np.sin(2 * np.pi * f0 * r * t) * np.exp(-t / d)
                   for r, d in ((1, 0.08), (2.76, 0.05), (5.4, 0.03))) * rng.uniform(0.4, 1.0)
    return place(6, np.sort(rng.uniform(0.1, 5.5, 14)), ping)


def chair():
    n = int(0.6 * FS)
    scrape = bp(rng.standard_normal(n), 200, 2500) * np.hanning(n) * (1 + 0.5 * np.sin(2 * np.pi * 35 * np.arange(n) / FS))
    return np.concatenate([scrape, burst(0.25, 50, 600, 0.04) * 3])


def voiced(seconds, f0):
    n = int(seconds * FS)
    t = np.arange(n) / FS
    pitch = f0 * (1 + 0.08 * np.sin(2 * np.pi * 0.7 * t) + 0.03 * np.sin(2 * np.pi * 3.1 * t))
    src = np.sign(np.sin(2 * np.pi * np.cumsum(pitch) / FS)) * 0.5 + 0.05 * rng.standard_normal(n)
    y = bp(src, 300, 900) + 0.6 * bp(src, 1000, 2400) + 0.2 * bp(src, 2500, 3500)
    return y * np.clip(np.sin(2 * np.pi * 2.2 * t + np.sin(2 * np.pi * 0.31 * t) * 3), 0, 1) ** 0.5


SOURCES_NOTE = """# Synthetic source signals

Generated by make_sources.py at 24 kHz, mono, peak-normalised to 0.8. All signals are
dry: they contain no reverberation and no microphone response.

| File | Class | Construction |
|---|---|---|
| walking.wav | footsteps | 8 steps at 0.55 s intervals; each a 60 to 900 Hz noise burst decaying in 30 ms (heel) followed 90 ms later by a 300 to 3000 Hz burst decaying in 15 ms (toe) |
| water.wav | water tap | 5 s of 500 to 9000 Hz noise with a slow random level fluctuation (1 to 12 Hz, about 25 %) |
| cooking.wav | cooking | 5 s of 2.5 to 10 kHz noise plus 120 random 3 to 11 kHz crackles of 20 ms |
| keyboard.wav | keyboard | 30 clicks of 1.5 to 9 kHz noise, 6 ms decay, 90 to 300 ms apart |
| cutlery.wav | cutlery | 14 pings: three inharmonic partials (ratios 1, 2.76, 5.4) at 2.2 to 3.8 kHz with 80, 50 and 30 ms decays |
| chair.wav | chair | 0.6 s scrape (200 to 2500 Hz noise, 35 Hz amplitude modulation) followed by a 50 to 600 Hz thud |
| talking.wav | speech | pulse train at 120 Hz with slow pitch movement, filtered into three formant bands (300 to 900, 1000 to 2400, 2500 to 3500 Hz), syllable rhythm about 2.2 Hz |
| tv.wav | tv | the same model at 190 Hz plus a quieter copy at 95 Hz |

Replace any file with a dry recording of the same name to use real material.
"""

SOUNDS = {
    "walking.wav": footsteps, "water.wav": water_tap, "cooking.wav": cooking,
    "keyboard.wav": keyboard, "cutlery.wav": cutlery, "chair.wav": chair,
    "talking.wav": lambda: voiced(6, 120), "tv.wav": lambda: voiced(6, 190) + 0.3 * voiced(6, 95),
}

if __name__ == "__main__":
    os.makedirs("SAMPLES", exist_ok=True)
    for name, make in SOUNDS.items():
        path = os.path.join("SAMPLES", name)
        if os.path.exists(path):
            print(f"  keeping existing {path}")
            continue
        x = make()
        x = x / np.max(np.abs(x)) * 0.8
        wavfile.write(path, FS, (x * 32767).astype(np.int16))
        print(f"  wrote {path}  ({len(x) / FS:.1f} s)")
    with open(os.path.join("SAMPLES", "SOURCES.md"), "w", encoding="utf-8") as f:
        f.write(SOURCES_NOTE)
